package com.hexora.hexora.report;

/**
 * The four deliverables planned for an audit project. All of them are generated from the same
 * {@link ReportSnapshot}; they differ in audience, format and the renderer that turns the snapshot
 * into a file.
 */
public enum ReportType {

    /** Technical PDF: CVE detail, CIA risk, mitigation plans and general summary. */
    TECNICO_PDF("TECNICO", "PDF", "application/pdf", "pdf", "informe-tecnico"),

    /** Formal, non-technical PDF for the client's management, with the same underlying facts. */
    EJECUTIVO_PDF("EJECUTIVO", "PDF", "application/pdf", "pdf", "informe-ejecutivo"),

    /** Compilation of the mitigation plans of the project's findings. */
    PLANES_MITIGACION_PDF("TECNICO", "PDF", "application/pdf", "pdf", "planes-mitigacion"),

    /** Risk matrices as a spreadsheet (.xlsx). */
    MATRIZ_RIESGO_XLSX("TECNICO", "XLSX",
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "xlsx", "matriz-riesgo");

    private final String audience;
    private final String format;
    private final String contentType;
    private final String extension;
    private final String fileNamePrefix;

    ReportType(String audience, String format, String contentType, String extension, String fileNamePrefix) {
        this.audience = audience;
        this.format = format;
        this.contentType = contentType;
        this.extension = extension;
        this.fileNamePrefix = fileNamePrefix;
    }

    public String audience() {
        return audience;
    }

    public String format() {
        return format;
    }

    public String contentType() {
        return contentType;
    }

    /** File name generated by the server only; user-supplied text never reaches it. */
    public String fileName(String reportPublicId) {
        String shortId = reportPublicId.length() >= 8 ? reportPublicId.substring(0, 8) : reportPublicId;
        return fileNamePrefix + "-" + shortId + "." + extension;
    }
}
